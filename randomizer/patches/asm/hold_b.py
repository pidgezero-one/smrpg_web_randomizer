"""HoldB: hold B to advance dialog instead of tapping.

Patches four sites with short JSL trampolines / hooks that route the
dialog-advance check through a small helper at ``$C2:FE90``.
"""


def get_patch() -> dict[int, bytes]:
    return {
        0x5D5E: bytes([0x20, 0x54, 0xF1]),
        0x15627: bytes([0x22, 0x90, 0xFE, 0xC2, 0x89, 0x80, 0x00]),
        0xF154: bytes([0x22, 0x90, 0xFE, 0xC2, 0x60]),
        0x2FE90: bytes([
            0xAF, 0x14, 0x30, 0x00, 0x0F, 0x11, 0x30, 0x00, 0x6B,
        ]),
    }
