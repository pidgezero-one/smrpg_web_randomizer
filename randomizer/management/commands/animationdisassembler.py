def tok(rom, start, end, bank):
    dex = start
    script = []
    while dex <= end:
        cmd = rom[dex]
        l = command_lens[cmd]
        bytestring = [('0x%02x' % i) for i in rom[dex:dex+l]]
        # print('0x%06x' % dex, bytestring)
        script.append((rom[dex:dex+l], dex))
        dex += l
    return script

