from django.core.management.base import BaseCommand
from randomizer.management.disassembler_common import shortify, bit, dbyte, hbyte, named, con, byte, byte_int, short, short_int, writeline, writeline_dialog
from randomizer.data.dialogs import decompress

ptrstart = 0x37E000
ptrend = 0x37FFFF
start = 0x220000
end = 0x249100

class Command(BaseCommand):

    def add_arguments(self, parser):
        parser.add_argument('-r', '--rom', dest='rom',
                            help='Path to a Mario RPG rom')

        parser.add_argument('-d', '--debug', action="store_true",
                            help='If set, dumps to a gitignored folder instead of overwriting the scripts sourced by SMRPG Randomizer')

    
    def handle(self, *args, **options):
        debug = options['debug']

        dest = 'randomizer/data'
        if debug:
            dest = 'randomizer/management/commands/output/disassembler'

        global rom
        rom = bytearray(open(options['rom'], 'rb').read())

        
        file = open("%s/dialog_table.py" % dest, "wb")
        file.write('# AUTOGENERATED DO NOT EDIT!!\n'.encode("utf8"))
        file.write('# Run the following command if you need to rebuild the table\n'.encode("utf8"))
        file.write('# python manage.py dialoguedisassembler --rom ROM\n'.encode("utf8"))
        file.write('dialogs = [None]*4096\n'.encode("utf8"))

        pointers = []
        raw_data = []

        

        for i in range(0, ptrend - ptrstart, 2):
            if (i >= 0xC00):
                pointers.append(((0x24 << 16) + 4) | (shortify(rom, ptrstart + i)))
            elif (i >= 0x800):
                pointers.append(((0x23 << 16) + 4) | (shortify(rom, ptrstart + i)))
            else:
                pointers.append(((0x22 << 16) + 8) | (shortify(rom, ptrstart + i)))
    

        for i in range(len(pointers)):
            if (i < len(pointers) - 1):
                raw_data.append(rom[pointers[i]:pointers[i + 1]])
            else:
                raw_data.append(rom[pointers[i]:end])

        for i in range(len(raw_data)):
            s = "".join(map(chr, raw_data[i]))
            t = decompress(s)
            file.write(("dialogs[%i] = '''%s'''\n" % (i, t)).encode("utf8"))
        
        file.close()