from django.core.management.base import BaseCommand
from randomizer.management.disassembler_common import shortify, bit, dbyte, hbyte, named, con, byte, byte_int, short, short_int, build_table, use_table_name, get_flag_string, flags, con_int, flags_short, writeline, bit_bool_from_num
from randomizer.data.roomobjecttables import object_type, event_initiator, post_battle_behaviour, radial_direction_table


start = 0x148400
end = 0x14FFFF
ptrstart = 0x148000
ptrend = 0x1483FF


class Command(BaseCommand):

    def add_arguments(self, parser):
        parser.add_argument('-r', '--rom', dest='rom',
                            help='Path to a Mario RPG rom')

    def handle(self, *args, **options):
        global rom
        rom = bytearray(open(options['rom'], 'rb').read())

        rooms_raw_data = []
        ptrs = []
        for i in range(ptrstart, ptrend, 2):

            ptrs.append((0x14 << 16) | (shortify(rom, i)))
        lengths = []

        # get raw data per room
        for i in range(len(ptrs)):
            if (i < len(ptrs) - 1):
                lengths.append(ptrs[i + 1] - ptrs[i])
                rooms_raw_data.append(rom[ptrs[i]:ptrs[i + 1]])
            else:
                lengths.append(end - ptrs[i])
                rooms_raw_data.append(rom[ptrs[i]:end])

        for i in range(len(rooms_raw_data)):
            d = rooms_raw_data[i]
            if (i <= 509):
            
                file = open("randomizer/data/roomobjects/room_%i.py" % i, "w")
                writeline(file, '# AUTOGENERATED DO NOT EDIT!!')
                writeline(file, '# Run the following command if you need to rebuild the table')
                writeline(file, '# python manage.py objectdisassembler --rom ROM')
                writeline(
                    file, 'from randomizer.data.roomobjecttables import ObjectType, Initiator, PostBattle, RadialDirection')

                if len(d) == 0:
                    writeline(file, 'room = None')
                else:
                    partition = d[0]
                    
                    writeline(file, 'room = {')
                    writeline(file, '  "partition": %i,' % partition)

                    offset = 1
                    writeline(file, '  "objects": [')
                    n = 0
                    while (offset < len(d)):
                        print ('0x%06x room %i npc %i ' % (ptrs[i] + offset, i, n))
                        l = 12

                        otype = d[offset] >> 4
                        obj_type, _ = byte(prefix="ObjectType", table=object_type)([d[offset] >> 4])

                        speed = d[offset + 1] & 0x07

                        assigned_npc = ((d[offset + 4] & 0x0F) << 6) | (d[offset + 3] >> 2)
                        action_scipt = ((d[offset + 5] & 0x3F) << 4) | ((d[offset + 4] & 0xFF) >> 4)

                        writeline(file, '    {')
                        writeline(file, '      "type": %s,' % obj_type)
                        initiator, _ = byte(prefix="Initiator", table=event_initiator)([d[offset + 7] >> 4])
                        writeline(file, '      "initiator": %s,' % initiator)
                        writeline(file, '      "model": %i,' % assigned_npc)
                        if otype <= 1:
                            event = ((d[offset + 7] & 0x0F) << 8) | d[offset + 6]
                            writeline(file, '      "event_script": %i,' % event)
                        elif otype == 2:
                            writeline(file, '      "battle_pack": %i,' % d[offset + 6])
                            writeline(file, '      "after_battle": %i,' % (d[offset + 7] & 0x0F))
                        writeline(file, '      "action_script": %i,' % action_scipt)
                        writeline(file, '      "speed": %i,' % speed)
                        if otype == 0:
                            writeline(file, '      "npc_id_offset": %i,' % (d[offset + 8] & 0x07))
                            writeline(file, '      "event_offset": %i,' % (d[offset + 8] >> 5))
                            writeline(file, '      "action_offset": %i,' % ((d[offset + 8] & 0x1F) >> 3))
                        elif otype == 1:
                            writeline(file, '      "star_offset": %i,' % (d[offset + 8] & 0x0F))
                            writeline(file, '      "item_offset": %i,' % (d[offset + 8] >> 4))
                        elif otype == 2:
                            writeline(file, '      "action_offset": %i,' % (d[offset + 8] & 0x0F))
                            writeline(file, '      "pack_offset": %i,' % (d[offset + 8] >> 4))
                        writeline(file, '      "visible": %r,' % bit_bool_from_num(d[offset + 9], 7))
                        writeline(file, '      "x": %i,' % (d[offset + 9] & 0x7F))
                        writeline(file, '      "y": %i,' % (d[offset + 10] & 0x7F))
                        writeline(file, '      "z": %i,' % (d[offset + 11] & 0x1F))
                        writeline(file, '      "z_half": %r,' % bit_bool_from_num(d[offset + 10], 7))
                        direction, _ = byte(prefix="RadialDirection", table=radial_direction_table)([d[offset + 11] >> 5])
                        writeline(file, '      "direction": %s,' % (direction))
                        writeline(file, '      "face_on_trigger": %r,' % bit_bool_from_num(d[offset + 1], 3))
                        writeline(file, '      "cant_enter_doors": %r,' % bit_bool_from_num(d[offset + 1], 4))
                        writeline(file, '      "byte2_bit5": %r,' % bit_bool_from_num(d[offset + 1], 5))
                        writeline(file, '      "set_sequence_playback": %r,' % bit_bool_from_num(d[offset + 1], 6))
                        writeline(file, '      "cant_float": %r,' % bit_bool_from_num(d[offset + 1], 7))
                        writeline(file, '      "cant_walk_up_stairs": %r,' % bit_bool_from_num(d[offset + 2], 0))
                        writeline(file, '      "cant_walk_under": %r,' % bit_bool_from_num(d[offset + 2], 1))
                        writeline(file, '      "cant_pass_walls": %r,' % bit_bool_from_num(d[offset + 2], 2))
                        writeline(file, '      "cant_jump_through": %r,' % bit_bool_from_num(d[offset + 2], 3))
                        writeline(file, '      "cant_pass_npcs": %r,' % bit_bool_from_num(d[offset + 2], 4))
                        writeline(file, '      "byte3_bit5": %r,' % bit_bool_from_num(d[offset + 2], 5))
                        writeline(file, '      "cant_walk_through": %r,' % bit_bool_from_num(d[offset + 2], 6))
                        writeline(file, '      "byte3_bit7": %r,' % bit_bool_from_num(d[offset + 2], 7))
                        writeline(file, '      "slidable_along_walls": %r,' % bit_bool_from_num(d[offset + 3], 0))
                        writeline(file, '      "cant_move_if_in_air": %r,' % bit_bool_from_num(d[offset + 3], 1))
                        writeline(file, '      "byte7_upper2": 0x%02x,' % (d[offset+5] >> 6))
                        n += 1
                        extra_length = d[offset] & 0x0F
                        if (extra_length > 0):
                            l += extra_length * 4
                            writeline(file, '      "clones": [')
                            
                            for o in range(offset + 12, offset + l - 1, 4):
                                print ('0x%06x room %i npc %i ' % (ptrs[i] + o, i, n))
                                writeline(file, '        {')
                                if otype == 0:
                                    writeline(file, '          "npc_id_offset": %i,' % (d[o] & 0x07))
                                    writeline(file, '          "event_offset": %i,' % (d[o] >> 5))
                                    writeline(file, '          "action_offset": %i,' % ((d[o] & 0x1F) >> 3))
                                elif otype == 1:
                                    writeline(file, '          "star_offset": %i,' % (d[o] & 0x0F))
                                    writeline(file, '          "item_offset": %i,' % (d[o] >> 4))
                                elif otype == 2:
                                    writeline(file, '          "action_offset": %i,' % (d[o] & 0x0F))
                                    writeline(file, '          "pack_offset": %i,' % (d[o] >> 4))
                                writeline(file, '          "visible": %r,' % bit_bool_from_num(d[o + 1], 7))
                                writeline(file, '          "x": %i,' % (d[o + 1] & 0x7F))
                                writeline(file, '          "y": %i,' % (d[o + 2] & 0x7F))
                                writeline(file, '          "z": %i,' % (d[o + 3] & 0x1F))
                                writeline(file, '          "z_half": %r,' % bit_bool_from_num(d[o + 2], 7))
                                direction, _ = byte(prefix="RadialDirection", table=radial_direction_table)([d[o + 3] >> 5])
                                writeline(file, '          "direction": %s' % (direction))
                                n += 1
                                if (o + 4 >= offset + l):
                                    writeline(file, '        }')
                                else:
                                    writeline(file, '        },')
                            writeline(file, '      ]')
                        else:
                            writeline(file, '      "clones": []')

                        if (offset + l < len(d)):
                            writeline(file, '    },')
                        else:
                            writeline(file, '    }')

                        offset += l
                    writeline(file, '  ]')

                    writeline(file, '}')

                file.close()

                """ print('%i @ 0x%06x' % (i, ptrs[i]))
                print('[')
                for j in d:
                    print('  0x%02x' % j)
                print(']') """
                # print ('[%s] # %i @ 0x%06x' % (" ".join(['0x%02x' % dx for dx in d]), i, ptrs[i]))

        file = open("randomizer/data/roomobjects/roomobjects.py",
                    "w", encoding='utf-8')
        for i in range(510):
            writeline(
                file, 'from randomizer.data.roomobjects.room_%i import room as room_%i' % (i, i))
        writeline(file, 'rooms = [None]*510')
        for i in range(510):
            writeline(file, 'rooms[%i] = room_%i' % (i, i))
        file.close()