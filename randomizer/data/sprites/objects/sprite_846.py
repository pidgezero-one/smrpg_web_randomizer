# SPR0846_SHARED_FREESTANDING_ITEMS
# GRIDPLANE (format 1, 24x32 = 3x4 subtiles). Format 0 (9 subtiles) rendered junk
# above each sprite in game -- the engine drew more subtiles than were authored, and
# format 1/12 is what ~140 vanilla gridplane molds use versus 10 for format 0. Gridplane is what lets this sprite ride
# a clone buffer, so room 422's sixteen same-sprite objects share ONE buffer region
# instead of each taking its own 4-slot dedicated allocation from the $6D cursor
# ($C0:8EBC allocates PER OBJECT). The 16x16 art sits bottom-aligned in columns 0-1;
# Empty grid cells MUST be real all-zero subtiles, not None: gridplane molds have no
# per-subtile presence mask (unlike non-gridplane byte0 bits 7-4), so the serializer
# writes all 9 ids and a None becomes subtile 0 -- which renders as junk.
# The art is re-composited at the PIXEL level: the 16x16 is decoded, placed into a
# 24x24 canvas at x=4 (centred) / y=8 (bottom), then re-encoded as 9 subtiles. The
# tile `x` field does NOT shift a gridplane mold (tried 124, no effect), and 4px is
# below what the 8px subtile grid can express, so pixel recompositing is the only way.
# Single sprite carrying every freestanding-prize graphic room 422 can show, so all
# fifteen of its prizes share ONE sprite_id and therefore one dedicated VRAM
# allocation. Each object picks its graphic with A_SetSpriteSequence(is_mold=True)
# after the standard room loader has created it.
#
# Palette is SPAL008 (gold) with NO offset. Frog coins are the SAME tiles in green,
# which is palette 8+2 = SPAL010; objects reach it with A_IncPaletteRowBy(2). That
# only works because the NPC record loads the extra rows -- see SHARED_ITEM_BASE in
# rooms/npcs.py (extra_palette_source_offset=1, extra_palette_row_count=2).

