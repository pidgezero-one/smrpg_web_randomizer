#
# SPAL255 (Red) and SPAL259 (Black) hold BYTE-IDENTICAL colours -- only the palette
# index differs -- so Black's tiles render correctly under Red's palette. Sharing one
# sprite therefore also shares one CGRAM row. Room 315 with the Axem Rangers as the
# seaside boss otherwise needs seven palette rows (9-15), leaving rows_remaining at 0,
# which silently downgrades the ship boss's crystal palette-swap merge to the canonical
# palette. Collapsing Red+Black to one palette frees the row that bump needs.
#
# Molds are copied verbatim from 466/485 and renumbered; both are gridplane format 3,
# so no recompositing is involved (contrast SPR0846, which had to be rebuilt at the
# pixel level). The Axems have no walking sprites -- sequence 0 is all room 315 plays.
# AnimationPack(0, length=0) follows SPR0846: the renderer allocates the pack.

